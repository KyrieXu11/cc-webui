import assert from "node:assert/strict";
import { SteerCoordinator } from "./steering";
const c = new SteerCoordinator();
let release!: () => void;
const order: string[] = [];
const a = c.submit("a", async () => { order.push("a"); await new Promise<void>(r => { release = r; }); return true; });
assert.equal(c.submit("a", async () => false), null, "double clicks reserve only once");
const b = c.submit("b", async () => { order.push("b"); return true; });
await Promise.resolve(); await Promise.resolve();
assert.deepEqual(order, ["a"]); release(); await a; await b;
assert.deepEqual(order, ["a", "b"]); assert.equal(c.has("a"), false);
let reject!: (e: Error) => void;
const stale = c.submit("same-id", () => new Promise<boolean>((_r, no) => { reject = no; }));
await Promise.resolve(); await Promise.resolve();
c.reset();
const next = c.submit("same-id", async () => true);
reject(new Error("old view disconnected"));
assert.equal((await stale!)?.stale, true); assert.equal((await next!)?.value, true);
console.log("steering.test.ts: all assertions passed");
