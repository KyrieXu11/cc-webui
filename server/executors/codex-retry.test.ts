import assert from "node:assert/strict";
import { CodexRetryTracker } from "./codex-retry.ts";
import type { CodexRetryFrame } from "../../shared/codex-retry.ts";
const frames: CodexRetryFrame[] = [];
const retry = new CodexRetryTracker(f => frames.push(f));
const accept = (method: string, p: Record<string, unknown>) => retry.accept(method, { turnId: "t", ...p }, "t");
accept("item/started", { item: { id: "old", type: "reasoning" } });
accept("error", { willRetry: false, error: { message: "terminal" } });
assert.equal(frames.length, 0);
accept("error", { turnId: "other", willRetry: true, error: { message: "other turn" } });
assert.equal(frames.length, 0);
accept("error", { willRetry: true, error: { message: "Reconnecting... 1/5", additionalDetails: "websocket closed by server before response.completed", codexErrorInfo: { responseStreamDisconnected: { httpStatusCode: 503 } }, raw_content: "DO_NOT_EXPOSE" } });
assert.deepEqual(frames[0], { type: "codex_retry", status: "retrying", turn_id: "t", message: "Reconnecting... 1/5", details: "websocket closed by server before response.completed", httpStatusCode: 503 });
assert(!JSON.stringify(frames).includes("DO_NOT_EXPOSE"));
accept("item/completed", { item: { id: "old", type: "reasoning" } });
accept("item/started", { item: { id: "user", type: "userMessage" } });
accept("item/commandExecution/outputDelta", { itemId: "tool", delta: "still running" });
accept("item/reasoning/textDelta", { itemId: "raw", delta: "DO_NOT_EXPOSE" });
assert.equal(frames.length, 1, "old item/user echo/tool output/raw reasoning cannot clear the retry status");
accept("item/started", { item: { id: "new", type: "reasoning" } });
assert.equal(frames.at(-1)?.status, "resumed");
accept("item/agentMessage/delta", { itemId: "answer", delta: "output" });
assert.equal(frames.length, 2, "recovery is emitted once");
accept("error", { willRetry: true, error: { message: "rate limit", codexErrorInfo: { httpConnectionFailed: { httpStatusCode: 429 } } } });
accept("item/reasoning/summaryTextDelta", { itemId: "new", delta: "visible summary" });
assert.equal(frames.at(-1)?.status, "resumed");
accept("error", { willRetry: true, error: { message: "again" } });
retry.end(); retry.end();
assert.deepEqual(frames.at(-1), { type: "codex_retry", status: "ended", turn_id: "t" });
assert.equal(frames.filter(f => f.status === "ended").length, 1);
console.log("Codex retry tracking uses native errors and scoped model progress only");
