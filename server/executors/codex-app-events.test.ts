import assert from "node:assert/strict";
import { CodexAppEvents } from "./codex-app-events.ts";
import { applySDKMessage } from "../../src/lib/processor.ts";
const frames: any[] = []; const decoder = new CodexAppEvents(f => frames.push(f));
decoder.accept("item/started", { turnId: "native-turn", item: { id: "tool", type: "commandExecution", command: "echo test", status: "inProgress" } });
decoder.accept("item/commandExecution/outputDelta", { turnId: "native-turn", itemId: "tool", delta: "actual output" });
decoder.accept("item/completed", { turnId: "native-turn", item: { id: "tool", type: "commandExecution", command: "echo test", status: "completed" } });
let events: any[] = [{ id: "initial-user", type: "user", text: "initial" }];
events = applySDKMessage(events, frames[0], () => {});
events = applySDKMessage(events, { type: "steer_user", id: "u-steer-q", text: "new direction" }, () => {});
events = applySDKMessage(events, frames[1], () => {}); events = applySDKMessage(events, frames[2], () => {});
assert.equal(events.filter(e => e.type === "step").length, 1, "mid-tool steer does not create a second tool row");
assert.equal(events.find(e => e.type === "step").output, "actual output");
events = applySDKMessage(events, { type: "steer_user", id: "u-steer-q", text: "new direction" }, () => {});
assert.equal(events.filter(e => e.id === "u-steer-q").length, 1);
decoder.accept("item/started", { turnId: "native-turn", item: { id: "reason", type: "reasoning", summary: [], content: ["DO_NOT_EXPOSE"] } });
assert(!JSON.stringify(frames.at(-1)).includes("DO_NOT_EXPOSE"));
decoder.accept("item/reasoning/summaryTextDelta", { turnId: "native-turn", itemId: "reason", summaryIndex: 0, delta: "visible summary" });
assert.equal(frames.at(-1).item.text, "visible summary");
decoder.accept("item/started", { turnId: "native-turn", item: { id: "patch", type: "fileChange", changes: [{ path: "a.md", kind: { type: "update", move_path: "b.md" }, diff: "@@ -1 +1 @@\n-old\n+new" }] } });
assert.equal(frames.at(-1).item.changes[0].move_path, "b.md");
assert.match(frames.at(-1).item.changes[0].diff, /-old/);
console.log("codex-app-events.test.ts: all assertions passed");
