import assert from "node:assert/strict";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import MessageList from "../src/components/MessageList.tsx";
import CodexRetryHint from "../src/components/CodexRetryHint.tsx";
import type { ChatEvent } from "../src/lib/types.ts";
const info = { kind: "codex" as const, turnId: "t", message: "Reconnecting... 1/5", details: "websocket closed by server before response.completed", httpStatusCode: 503 };
const html = renderToStaticMarkup(createElement(CodexRetryHint, { info }));
assert.match(html, /role="status"/); assert.match(html, /Codex 正在自动重试/);
assert.match(html, /Reconnecting\.\.\. 1\/5/); assert.match(html, /HTTP 503/); assert.match(html, /查看原生原因/);
assert.doesNotMatch(html, /Retrying in|attempt 0|倒计时/);
const escaped = renderToStaticMarkup(createElement(CodexRetryHint, { info: { ...info, message: '<script>alert("no")</script>' } }));
assert.doesNotMatch(escaped, /<script>/); assert.match(escaped, /&lt;script&gt;/);
const events: ChatEvent[] = [{ id: "u", type: "user", text: "test" }, { id: "t-codex-t-reason", type: "thinking", status: "pending", text: "" }];
const retrying = renderToStaticMarkup(createElement(MessageList, { events, expandedSteps: new Set<string>(), onToggleStep() {}, onAnswerPermission() {}, provider: "codex", isRunning: true, retryInfo: info }));
assert.match(retrying, /data-codex-retry="true"/); assert.doesNotMatch(retrying, /aria-label="Codex 思考中"/);
assert.match(retrying, /data-timeline-row="t-codex-t-reason"/, "retry pauses but does not unmount pending reasoning");
const claude = renderToStaticMarkup(createElement(MessageList, { events: [], expandedSteps: new Set<string>(), onToggleStep() {}, onAnswerPermission() {}, provider: "claude", retryInfo: { attempt: 2, maxRetries: 5, retryDelayMs: 3000, errorStatus: 429 } }));
assert.match(claude, /Retrying in 3s · attempt 2\/5 · HTTP 429/); assert.doesNotMatch(claude, /data-codex-retry/);
console.log("Retry rendering: native cause/status, preserved Claude behavior and pending thinking mount");
